import { expect, test } from "@playwright/test"
import fs from "node:fs"
test.setTimeout(60_000)
const SCRIPT = "캐시는 최근 결과를 5분 동안 저장합니다. 같은 요청에는 저장한 결과를 다시 사용합니다. 효과는 아직 검증하지 않았습니다."

test("S8 학생이 개념·쉬운 대본·예상 질문·자기 설명을 실제 AI로 확인하고 원문을 복원한다", async ({ page }, info) => {
  const evidence: { task: string, model: string, durationMs: number, httpStatus: number }[] = []
  await page.goto("/")
  await page.getByRole("button", { name: "바로 서비스 이용하기", exact: true }).click()
  await page.getByRole("link", { name: "대본 이해 연습", exact: true }).click()
  await page.getByLabel("분석할 대본 구간", { exact: true }).fill(SCRIPT)
  await page.getByLabel("근거 자료 (선택)", { exact: true }).fill(SCRIPT)
  const concepts = page.waitForResponse(r => r.url().endsWith("/api/coach") && r.request().method() === "POST" && r.request().postDataJSON().task === "concepts")
  await page.getByRole("button", { name: "낯선 개념 살펴보기", exact: true }).click()
  const conceptResponse = await concepts, conceptData = await conceptResponse.json()
  expect(conceptResponse.ok()).toBe(true)
  expect(conceptData.result.concepts.length).toBeGreaterThan(0)
  await expect(page.locator("#concept-list article").first()).toBeVisible()
  evidence.push({ task: "concepts", model: conceptData.model, durationMs: conceptData.durationMs, httpStatus: conceptResponse.status() })
  const rewrite = page.waitForResponse(r => r.url().endsWith("/api/coach") && r.request().method() === "POST" && r.request().postDataJSON().task === "rewrite")
  await page.getByRole("button", { name: "쉬운 대본 제안", exact: true }).click()
  const rewriteResponse = await rewrite, rewriteData = await rewriteResponse.json()
  expect(rewriteResponse.ok()).toBe(true)
  await expect(page.locator("#proposed-script")).toHaveValue(/5분/)
  await expect(page.getByRole("button", { name: "새 버전으로 적용", exact: true })).toBeDisabled()
  evidence.push({ task: "rewrite", model: rewriteData.model, durationMs: rewriteData.durationMs, httpStatus: rewriteResponse.status() })
  await page.getByRole("checkbox", { name: /수치·조건·부정·한계와 핵심 의미를 확인했어요/ }).check()
  await page.getByRole("button", { name: "새 버전으로 적용", exact: true }).click()
  await expect(page.locator("#revision")).toContainText("새 대본 버전으로 저장했어요")
  const question = page.waitForResponse(r => r.url().endsWith("/api/coach") && r.request().method() === "POST" && r.request().postDataJSON().task === "question")
  await page.getByRole("button", { name: "예상 질문 연습", exact: true }).click()
  const questionResponse = await question, questionData = await questionResponse.json()
  expect(questionResponse.ok()).toBe(true)
  expect(questionData.result.question.trim().length).toBeGreaterThan(0)
  await expect(page.locator("#question-text")).toHaveText(questionData.result.question)
  evidence.push({ task: "question", model: questionData.model, durationMs: questionData.durationMs, httpStatus: questionResponse.status() })
  await page.getByLabel("내 설명·답변", { exact: true }).fill("최근 결과를 5분 보관했다가 같은 요청에 다시 써요. 효과는 아직 확인한 게 아니에요.")
  const review = page.waitForResponse(r => r.url().endsWith("/api/coach") && r.request().method() === "POST" && r.request().postDataJSON().task === "review")
  await page.getByRole("button", { name: "답변 함께 확인", exact: true }).click()
  const reviewResponse = await review, reviewData = await reviewResponse.json()
  expect(reviewResponse.ok()).toBe(true)
  expect(["supported", "needs-work", "uncertain"]).toContain(reviewData.result.state)
  await expect(page.locator("#feedback")).toContainText("모델의 검토 초안이에요")
  await expect(page.locator("#attempt-history")).toContainText("전체 답변 1개")
  evidence.push({ task: "review", model: reviewData.model, durationMs: reviewData.durationMs, httpStatus: reviewResponse.status() })
  await page.getByRole("button", { name: "처음 대본으로 되돌리기", exact: true }).click()
  await expect(page.getByLabel("분석할 대본 구간", { exact: true })).toHaveValue(SCRIPT)
  expect(evidence).toHaveLength(4)
  expect(evidence.every(e => /^[a-z0-9-]+\//.test(e.model) && e.httpStatus === 200)).toBe(true)
  const output = info.outputPath("S8-actual-ai-evidence.json")
  fs.writeFileSync(output, JSON.stringify(evidence, null, 2))
  await info.attach("actual-ai-evidence", { path: output, contentType: "application/json" })
})
