import {test,expect} from '@playwright/test'
const SCRIPT='캐시는 최근 결과를 5분 동안 저장해 같은 요청에 다시 사용합니다.\n\n효과는 아직 검증하지 않았습니다.'

test('S5 확인한 대본 위치에서 대화하고 수정안을 확인·적용한 뒤 다시 연습한다',async({page})=>{
 const errors:string[]=[];let transcriptions=0;page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.url().endsWith('/api/transcribe')&&r.method()==='POST')transcriptions++})
 await page.goto('/studio.html');await page.getByRole('button',{name:'바로 서비스 이용하기'}).click()
 await page.getByLabel('발표 대본').fill(SCRIPT)
 await page.getByRole('button',{name:'카메라 확인하기'}).click()
 await page.getByRole('button',{name:'녹화 시작'}).click()
 await page.waitForTimeout(1200)
 await page.getByRole('button',{name:'연습 종료',exact:true}).click()
 await page.getByRole('button',{name:'이 시점의 대본 확인'}).click()
 await page.getByRole('button',{name:/캐시는 최근 결과를/}).click()
 await page.getByRole('button',{name:'이 문장으로 할게요',exact:true}).click()
 await page.getByRole('button',{name:'AI 코칭 시작',exact:true}).click()
 await expect(page.getByRole('heading',{name:'이 순간을 함께 돌아볼까요?'})).toBeVisible()
 await expect(page.getByRole('button',{name:'동의하고 대화 시작'})).toBeDisabled()
 await page.getByRole('checkbox',{name:/선택한 대본·근거 자료·답변/}).check()
 await page.getByRole('button',{name:'동의하고 대화 시작'}).click()
 await expect(page.getByText(/자동으로 감지한 이상 구간이라는 뜻은 아니에요/)).toBeVisible()
 await page.getByRole('button',{name:'문장이 말하기 어색했어요',exact:true}).click()
 await expect(page.getByText('문장의 어느 부분이 말하기 어려웠나요?',{exact:true})).toBeVisible()
 await page.getByLabel('답변 입력').fill('문장이 길어서 말하기 힘들었어요.')
 await page.getByRole('button',{name:'보내기',exact:true}).click()
 await expect(page.getByText('대화 요약',{exact:true})).toBeVisible()
 const revise=page.getByRole('button',{name:'이 문단 고치기',exact:true})
 if(process.env.STUDIO_EXPECT_READY==='1')await expect(revise).toBeEnabled()
 if(await revise.isDisabled()){await expect(page.getByText(/AI 미설정: 풀이/)).toBeVisible();expect(errors).toEqual([]);expect(transcriptions).toBe(0);return}
 const responsePromise=page.waitForResponse(r=>r.url().endsWith('/api/scripts/revise-segment')&&r.request().method()==='POST',{timeout:115000})
 await revise.click()
 const response=await responsePromise;expect(response.ok(), 'revision HTTP status '+response.status()).toBe(true)
 await expect(page.getByText('수정안이 준비됐어요',{exact:true})).toBeVisible({timeout:115000})
 await expect(page.getByRole('button',{name:'수정안 적용하기'})).toBeDisabled()
 await page.getByRole('checkbox',{name:/수치·조건·부정 표현과 원래 뜻/}).check()
 await page.getByRole('button',{name:'수정안 적용하기',exact:true}).click()
 await expect(page.getByRole('heading',{name:/달라진 문장으로 다시/})).toBeVisible()
 await page.getByRole('button',{name:'구간 녹화 시작',exact:true}).click()
 await page.waitForTimeout(1200)
 await page.getByRole('button',{name:'구간 연습 종료',exact:true}).click()
 await expect(page.getByTestId('practice-compare')).toBeVisible()
 expect(transcriptions).toBe(0);expect(errors).toEqual([])

 await page.getByRole('button',{name:'수정 전 대본으로 되돌리기',exact:true}).click()
 await expect(page.getByLabel('발표 대본')).toHaveValue(SCRIPT)

})
